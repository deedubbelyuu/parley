// Takes screenshots of the main UI states into /tmp/shots (for eyeballing design changes).
const fs = require('fs');
const http = require('http');
const H = require('./harness');
const FX = '/tmp/fx';
(async () => {
  fs.mkdirSync('/tmp/shots', { recursive: true });
  const srv = await H.startServer({ PREVIEW_ALLOW_PRIVATE: '1' });
  const png = fs.readFileSync(`${FX}/photo.png`);
  const site = http.createServer((req, res) => {
    if (req.url.startsWith('/pic.png')) return res.writeHead(200, { 'Content-Type': 'image/png' }), res.end(png);
    res.writeHead(200, { 'Content-Type': 'text/html' });
    if (req.url.startsWith('/article')) return res.end('<meta property="og:title" content="Fluffy buttermilk pancakes in 20 minutes"><meta property="og:site_name" content="Breakfast Weekly"><meta property="og:description" content="The trick is resting the batter for five minutes, and a hot, lightly buttered pan."><meta property="og:image" content="/pic.png">');
    res.end('<meta property="og:title" content="Big Buck Bunny — official trailer"><meta property="og:type" content="video.other"><meta property="og:site_name" content="YouTube"><meta property="og:description" content="Blender Foundation"><meta property="og:image" content="/pic.png">');
  }).listen(3997);
  const A = await H.launchElectron([`--use-file-for-fake-audio-capture=${FX}/noise.wav`]);
  const B = await H.launchChrome();
  const a = A.page;
  const b = B.page;
  const shot = (p, name) => p.screenshot({ path: `/tmp/shots/${name}.png` });
  try {
    for (const p of [a, b]) await p.evaluate(() => localStorage.setItem('parley:autoHideUi', 'false'));
    await shot(a, '0-login');
    await H.login(a, 'Alice', true);
    await H.login(b, 'Bob', false);
    await a.setInputFiles('#avatarFile', `${FX}/photo.png`);
    await H.openContact(b, 'Alice');
    await H.openContact(a, 'Bob');
    const say = async (p, t) => {
      await p.fill('#msgInput', t);
      await p.press('#msgInput', 'Enter');
      await H.sleep(150);
    };
    await say(b, 'hey! are we still on for tonight?');
    await say(b, 'I can bring the snacks 🍿');
    await say(a, 'yes!! 7pm works');
    await say(a, 'I’ll set up the movie — *popcorn* is on me');
    await say(b, '😂');
    await a.click('#emojiBtn');
    await a.click('#picker .tab[data-tab=stickers]');
    await a.click('#pickerStickers .sticker-grid button[title="Love"]');
    await a.setInputFiles('#attachFile', `${FX}/photo.png`);
    await H.sleep(300);
    await shot(a, '1a-tray');
    await a.click('#sendBtn');
    await H.sleep(1500);
    await b.setInputFiles('#attachFile', `${FX}/doc.bin`);
    await b.click('#sendBtn');
    await H.sleep(1500);
    await say(a, 'trailer: http://localhost:3997/watch');
    await say(b, 'https://www.youtube.com/watch?v=aqz-KE-bpKQ&si=AbCdEfGhIjKlMnOp&pp=ygUJYnVubnk%3D');
    await say(b, 'and breakfast after? http://localhost:3997/article');
    await H.sleep(1500);
    await b.hover('.msg.in:has-text("7pm works") .bubble');
    await b.click('.msg.in:has-text("7pm works") .msg-actions .emo[title="React ❤️"]');
    await b.hover('.msg.in:has-text("7pm works") .bubble');
    await b.click('.msg.in:has-text("7pm works") .msg-actions button[title=Reply]');
    await say(b, 'perfect, see you then');
    await H.sleep(800);
    await a.mouse.move(10, 10);
    await shot(a, '1-chat');
    await shot(b, '2-chat-bob-web');
    await a.hover('.msg.in:has-text("see you then") .bubble');
    await H.sleep(200);
    await shot(a, '2b-hover-actions');
    await a.click('.msg.in:has-text("see you then") .bubble', { button: 'right' });
    await H.sleep(200);
    await shot(a, '2c-context-menu');
    await a.keyboard.press('Escape');
    await a.click('#statusBtn');
    await H.sleep(200);
    await shot(a, '2d-status-menu');
    await a.keyboard.press('Escape');
    await a.hover('.msg.out:has-text("popcorn") .bubble');
    await a.click('.msg.out:has-text("popcorn") .msg-actions button[title=Reply]');
    await a.fill('#msgInput', 'typing a reply…');
    await shot(a, '2e-replying');
    await a.keyboard.press('Escape');
    await a.fill('#msgInput', '');
    await a.click('#emojiBtn');
    await a.click('#picker .tab[data-tab=emoji]');
    await H.sleep(200);
    await shot(a, '3-emoji-picker');
    await a.keyboard.press('Escape');
    await a.click('#settingsBtn');
    await H.sleep(900);
    await shot(a, '5-settings-top');
    await a.evaluate(() => document.querySelector('.settings-card').scrollTo(0, 99999));
    await H.sleep(200);
    await shot(a, '6-settings-bottom');
    await a.click('#themeGrid .theme[data-theme=light]');
    await a.click('#settingsDone');
    await H.sleep(300);
    await shot(a, '7-theme-light');
    await a.click('#settingsBtn');
    await a.click('#themeGrid .theme[data-theme=midnight]');
    await a.click('#settingsDone');
    await H.connectCall(a, b);
    await H.sleep(2500);
    await a.mouse.move(400, 300);
    await shot(a, '8-call');
    await a.click('#micBtn');
    await H.sleep(1500);
    await shot(a, '8b-call-muted');
    await a.click('#micBtn');
    await a.click('#screenBtn');
    await a.waitForSelector('#screenPicker:not(.hidden) .source', { timeout: 8000 });
    await shot(a, '8c-screen-picker');
    await a.click('#sourceGrid .source');
    await b.waitForFunction(() => document.querySelector('#stage').classList.contains('has-screen'), null, { timeout: 10000 });
    await H.sleep(2000);
    await b.mouse.move(400, 300);
    await shot(b, '8d-bob-sees-screen-and-cam');
    await shot(a, '8e-alice-sharing');
    await a.click('#shareStopBtn');
    await a.setInputFiles('#mediaFile', `${FX}/movie.mp4`);
    await b.waitForFunction(() => document.querySelector('#mediaVideo').videoWidth > 0, null, { timeout: 15000 });
    await H.sleep(2500);
    await b.mouse.move(400, 300);
    await shot(b, '9-bob-watching');
    await a.click('#chatPanelBtn');
    await say(b, 'this is great');
    await H.sleep(500);
    await a.mouse.move(400, 300);
    await shot(a, '9b-chat-hidden-badge');
    await a.click('#chatPanelBtn');
    const p = A.app.waitForEvent('window');
    await A.app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.executeJavaScript('window.__parleyMini.open()', true));
    const mini = await p;
    await H.sleep(1500);
    await mini.mouse.move(100, 100);
    await H.sleep(200);
    await mini.screenshot({ path: '/tmp/shots/10-mini.png' });
    await a.click('#mediaStopBtn');
    await H.sleep(1500);
    await mini.mouse.move(120, 110);
    await H.sleep(200);
    await mini.screenshot({ path: '/tmp/shots/11-mini-cam.png' });
  } catch (e) {
    console.log('screens failed:', e.message);
  } finally {
    await A.app.close().catch(() => {});
    await B.browser.close().catch(() => {});
    srv.kill();
    site.close();
  }
})();
